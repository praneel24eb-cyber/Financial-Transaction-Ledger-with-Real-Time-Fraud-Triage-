import json
import logging
from typing import Dict, Any
from backend.app.repositories.db import db_manager

logger = logging.getLogger(__name__)

# SHA-256 over the same canonical representation the PostgreSQL audit trigger uses
# (jsonb text form), so app-written and trigger-written audit rows share one hash chain:
# row_hash = SHA256(prev_hash | table_name | operation | old_data | new_data)
# See backend/app/database/triggers.sql -> audit_trigger_func().

class AuditService:
    @staticmethod
    def record_audit_entry(conn, table_name: str, operation: str, old_data: dict = None, new_data: dict = None):
        """
        Inserts an append-only hash-chained row into AUDIT_LOG within an existing transaction.

        Both prev_hash and row_hash are computed by PostgreSQL so hashes produced here are
        byte-identical to the ones generated by the audit_trigger_func() triggers.
        """
        old_json = json.dumps(old_data) if old_data is not None else None
        new_json = json.dumps(new_data) if new_data is not None else None

        with conn.cursor() as cur:
            cur.execute("SELECT row_hash FROM AUDIT_LOG ORDER BY audit_id DESC LIMIT 1;")
            row = cur.fetchone()
            prev_hash = row['row_hash'] if row and row.get('row_hash') else "0" * 64

            query = """
                INSERT INTO AUDIT_LOG (table_name, operation, old_data, new_data, prev_hash, row_hash, created_at)
                VALUES (
                    %s, %s, %s::jsonb, %s::jsonb, %s,
                    encode(digest(%s || '|' || %s || '|' || %s || '|' ||
                                   COALESCE(%s::jsonb::text, '') || '|' ||
                                   COALESCE(%s::jsonb::text, ''), 'sha256'), 'hex'),
                    NOW()
                );
            """
            cur.execute(query, (
                table_name, operation, old_json, new_json, prev_hash,
                prev_hash, table_name, operation, old_json, new_json
            ))

    @staticmethod
    def verify_hash_chain() -> Dict[str, Any]:
        """
        Scans all AUDIT_LOG rows sequentially from audit_id = 1.
        Re-calculates every SHA-256 row_hash in PostgreSQL and verifies the prev_hash link.
        Returns: { 'is_valid': bool, 'total_rows': int, 'tampered_audit_id': Optional[int], 'message': str }
        """
        with db_manager.get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    WITH chain AS (
                        SELECT audit_id, table_name, operation, old_data, new_data, prev_hash, row_hash,
                               LAG(row_hash) OVER (ORDER BY audit_id ASC) AS expected_prev_hash
                        FROM AUDIT_LOG
                    )
                    SELECT audit_id, prev_hash, row_hash, expected_prev_hash,
                           encode(digest(COALESCE(prev_hash, REPEAT('0', 64)) || '|' ||
                                         table_name || '|' || operation || '|' ||
                                         COALESCE(old_data::text, '') || '|' ||
                                         COALESCE(new_data::text, ''), 'sha256'), 'hex') AS recomputed_row_hash
                    FROM chain
                    ORDER BY audit_id ASC;
                """)

                rows = cur.fetchall()

                if not rows:
                    return {
                        "is_valid": True,
                        "total_rows": 0,
                        "tampered_audit_id": None,
                        "message": "Audit log is empty. Chain intact."
                    }

                for r in rows:
                    audit_id = r['audit_id']
                    stored_prev_hash = r['prev_hash'] or "0" * 64
                    stored_row_hash = r['row_hash']
                    expected_prev_hash = r['expected_prev_hash'] or "0" * 64

                    # Check 1: prev_hash linkage match
                    if stored_prev_hash != expected_prev_hash:
                        return {
                            "is_valid": False,
                            "total_rows": len(rows),
                            "tampered_audit_id": audit_id,
                            "message": f"Tampering detected at audit_id {audit_id}: stored prev_hash does not match previous row's row_hash."
                        }

                    # Check 2: recompute current row_hash from row content
                    if r['recomputed_row_hash'] != stored_row_hash:
                        return {
                            "is_valid": False,
                            "total_rows": len(rows),
                            "tampered_audit_id": audit_id,
                            "message": f"Tampering detected at audit_id {audit_id}: row content does not match stored SHA-256 row_hash."
                        }

                return {
                    "is_valid": True,
                    "total_rows": len(rows),
                    "tampered_audit_id": None,
                    "message": f"Verified {len(rows)} audit rows. Hash chain is 100% valid and tamper-free."
                }

audit_service = AuditService()
